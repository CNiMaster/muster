/** 生成 persona 正文（与现有格式对齐：身份与记忆/核心使命/关键规则/技术交付物/工作流程/成功指标）。 */
function buildBody(domainLabel, role) {
  const lines = [];
  lines.push(`# ${role.name} Agent 人格`);
  lines.push('');
  lines.push(`你是 **${role.name}**，${role.description}。你以专业标准完成工作，主动对齐目标并交付可验证的成果。`);
  lines.push('');
  lines.push('## 你的身份与记忆');
  lines.push('');
  lines.push(`- **角色**：${domainLabel}领域的${role.name}`);
  lines.push('- **个性**：专业、细致、目标导向、主动反馈风险');
  lines.push('- **记忆**：你记住每一次成功案例与失败教训，形成可复用的方法沉淀');
  lines.push('- **经验**：你熟悉本领域的行业规范、交付标准与协作方式');
  lines.push('');
  lines.push('## 核心使命');
  lines.push('');
  for (const item of role.mission) {
    lines.push(`- ${item}`);
  }
  lines.push('');
  lines.push('## 关键规则');
  lines.push('');
  for (const rule of role.rules) {
    lines.push(`- ${rule}`);
  }
  lines.push('');
  lines.push('## 技术交付物');
  lines.push('');
  for (const item of role.deliverables) {
    lines.push(`- ${item}`);
  }
  lines.push('');
  lines.push('## 工作流程');
  lines.push('');
  for (const item of role.workflow) {
    lines.push(`- ${item}`);
  }
  lines.push('');
  lines.push('## 成功指标');
  lines.push('');
  for (const item of role.metrics) {
    lines.push(`- ${item}`);
  }
  lines.push('');
  lines.push('## 沟通风格');
  lines.push('');
  lines.push('- 简洁直接，先结论后依据');
  lines.push('- 主动暴露风险与依赖，不隐瞒问题');
  lines.push('- 交付时说明做了什么、为什么、验证结果');
  lines.push('');
  return lines.join('\n');
}

let total = 0;
const domainsJson = {};
for (const [domain, def] of Object.entries(DOMAINS)) {
  const dir = path.join(PERSONAS_ROOT, domain);
  mkdirSync(dir, { recursive: true });
  const personas = [];
  for (const role of def.roles) {
    const content = [
      '---',
      `name: ${role.name}`,
      `description: ${role.description}`,
      `emoji: ${role.emoji}`,
      'color: "#4A90D9"',
      '---',
      '',
      buildBody(def.label, role),
    ].join('\n');
    writeFileSync(path.join(dir, `${role.id}.md`), content, 'utf8');
    personas.push(role.id);
    total++;
    console.log(`✓ ${domain}/${role.id}.md`);
  }
  domainsJson[domain] = { label: def.label, count: personas.length, personas };
}

